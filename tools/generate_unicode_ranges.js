const fs = require('fs');
const path = require('path');

const isLetterOrNumber = /[\p{L}\p{N}\p{M}_]+/u
const ranges = [];
let rangeStart = null;
let previous = null;

for (let codePoint = 0; codePoint <= 0x10ffff; codePoint++) {
  const included = codePoint === 0x5f || isLetterOrNumber.test(String.fromCodePoint(codePoint));

  if (included && rangeStart === null) {
    rangeStart = codePoint;
  } else if (!included && rangeStart !== null) {
    ranges.push([rangeStart, previous]);
    rangeStart = null;
  }

  if (included) previous = codePoint;
}

if (rangeStart !== null) ranges.push([rangeStart, previous]);

const formatCodePoint = (codePoint) => `0x${codePoint.toString(16).toUpperCase()}`;
const rows = ranges.map(([start, end]) => `  {${formatCodePoint(start)}, ${formatCodePoint(end)}}`).join(',\n');
const output = `/* Generated by tools/generate_unicode_ranges.js. */
#ifndef TREE_SITTER_NAMUMARK_UNICODE_RANGES_H_
#define TREE_SITTER_NAMUMARK_UNICODE_RANGES_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef struct {
  uint32_t start;
  uint32_t end;
} UnicodeRange;

static const UnicodeRange UNICODE_LETTER_NUMBER_RANGES[] = {
${rows}
};

static bool is_unicode_letter_or_number(uint32_t code_point) {
  size_t low = 0;
  size_t high = sizeof(UNICODE_LETTER_NUMBER_RANGES) /
                sizeof(UNICODE_LETTER_NUMBER_RANGES[0]);

  while (low < high) {
    size_t middle = low + (high - low) / 2;
    UnicodeRange range = UNICODE_LETTER_NUMBER_RANGES[middle];

    if (code_point < range.start) {
      high = middle;
    } else if (code_point > range.end) {
      low = middle + 1;
    } else {
      return true;
    }
  }

  return false;
}

#endif
`;

const outputPath = path.resolve(__dirname, '..', 'src', 'unicode_ranges.h');
fs.writeFileSync(outputPath, output);
console.log(`Generated ${ranges.length} Unicode ranges at ${outputPath}`);
